#!/usr/bin/env python3
"""
Builds Install-Starfall-Valley.lua: one script that puts the whole game into
whatever place you have open in Roblox Studio.

It follows the same layout rules as Rojo (default.project.json):
  src/shared  -> ReplicatedStorage.Shared                     (Folder of ModuleScripts)
  src/server  -> ServerScriptService.Server                   (Script; init.server.luau + child modules)
  src/client  -> StarterPlayer.StarterPlayerScripts.Client    (LocalScript; init.client.luau + child modules)

Run from roblox/game:   python3 tools/make_installer.py
"""
import re
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent
SRC = GAME / "src"
OUT = GAME / "Install-Starfall-Valley.lua"

# (service path, root name, src folder, root class, init file)
ROOTS = [
    (["ReplicatedStorage"], "Shared", "shared", "Folder", None),
    (["ServerScriptService"], "Server", "server", "Script", "init.server.luau"),
    (["StarterPlayer", "StarterPlayerScripts"], "Client", "client", "LocalScript", "init.client.luau"),
]


def long_string(text: str) -> str:
    """Wraps text in a Lua long string whose level never appears inside it."""
    level = 1
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    # The newline right after the opening bracket is dropped by Lua, so the
    # source keeps its exact first line.
    return f"[{eq}[\n{text}]{eq}]"


def lua_list(items):
    return "{ " + ", ".join(f'"{i}"' for i in items) + " }"


def main():
    entries = []
    for service_path, root_name, folder, root_class, init_file in ROOTS:
        directory = SRC / folder
        root_source = (directory / init_file).read_text() if init_file else None
        entries.append((service_path, root_name, root_class, root_source, []))
        children = entries[-1][4]
        for path in sorted(directory.glob("*.luau")):
            if path.name == init_file:
                continue
            name = re.sub(r"\.luau$", "", path.name)
            children.append((name, "ModuleScript", path.read_text()))

    total_files = sum((1 if src is not None else 0) + len(c) for _, _, _, src, c in entries)
    lines = []
    w = lines.append
    w("--[[")
    w("\tSTARFALL VALLEY: one-step installer")
    w("")
    w("\tPuts the whole game into the place you have open in Roblox Studio.")
    w("")
    w("\tHow to run it (pick one):")
    w("\t  A) Model tab -> Run Script -> pick this file.")
    w("\t  B) View tab -> Command Bar, paste this whole file in, press Enter.")
    w("")
    w("\tThen press Play (F5).")
    w("")
    w("\tSafe to run again: it replaces only its own scripts. Ctrl+Z undoes it.")
    w("\tThis file is generated by tools/make_installer.py from roblox/game/src.")
    w("\tDon't edit it by hand: edit src/, then run the generator again.")
    w("]]")
    w("")
    w('local ChangeHistoryService = game:GetService("ChangeHistoryService")')
    w('local TAG = "StarfallValley"')
    w("")
    w("local recording = nil")
    w("pcall(function()")
    w('\trecording = ChangeHistoryService:TryBeginRecording("Install Starfall Valley")')
    w("end)")
    w("")
    w("local function serviceAt(path)")
    w("\tlocal node = game:GetService(path[1])")
    w("\tfor i = 2, #path do")
    w("\t\tnode = node:FindFirstChild(path[i]) or node:WaitForChild(path[i], 5)")
    w("\tend")
    w("\treturn node")
    w("end")
    w("")
    w("-- Replaces our own earlier install; renames anything else with the same")
    w("-- name instead of deleting it, so nothing of yours is ever lost.")
    w("local function freeName(parent, name)")
    w("\tlocal existing = parent:FindFirstChild(name)")
    w("\twhile existing do")
    w("\t\tif existing:GetAttribute(TAG) then")
    w("\t\t\texisting:Destroy()")
    w("\t\telse")
    w('\t\t\texisting.Name = name .. "_Backup"')
    w('\t\t\tprint("[Starfall Valley] Renamed your existing " .. parent.Name .. "." .. name .. " to " .. name .. "_Backup")')
    w("\t\tend")
    w("\t\texisting = parent:FindFirstChild(name)")
    w("\tend")
    w("end")
    w("")
    w("local function make(className, name, parent, source)")
    w("\tlocal instance = Instance.new(className)")
    w("\tinstance.Name = name")
    w("\tif source then")
    w("\t\tinstance.Source = source")
    w("\tend")
    w("\tinstance:SetAttribute(TAG, true)")
    w("\tinstance.Parent = parent")
    w("\treturn instance")
    w("end")
    w("")
    w("local created = 0")
    w("")
    for service_path, root_name, root_class, root_source, children in entries:
        w(f"-- {'.'.join(service_path)}.{root_name}")
        w("do")
        w(f"\tlocal parent = serviceAt({lua_list(service_path)})")
        w(f'\tfreeName(parent, "{root_name}")')
        if root_source is None:
            w(f'\tlocal root = make("{root_class}", "{root_name}", nil, nil)')
        else:
            w(f'\tlocal root = make("{root_class}", "{root_name}", nil, {long_string(root_source)})')
            w("\tcreated += 1")
        for name, cls, source in children:
            w(f'\tmake("{cls}", "{name}", root, {long_string(source)})')
            w("\tcreated += 1")
        # parent last, so a script never starts with half its modules missing
        w("\troot.Parent = parent")
        w("end")
        w("")
    w("-- Player settings (same as default.project.json)")
    w("pcall(function()")
    w('\tlocal starterPlayer = game:GetService("StarterPlayer")')
    w("\tstarterPlayer.CharacterWalkSpeed = 16")
    w("\tstarterPlayer.CharacterUseJumpPower = true")
    w("\tstarterPlayer.CharacterJumpPower = 50")
    w("\tstarterPlayer.CameraMaxZoomDistance = 60")
    w("end)")
    w("")
    w("-- Build the world now, so you can see it in Studio before pressing Play.")
    w("-- (The server rebuilds it the same way every time the game starts.)")
    w("local previewOk, previewErr = pcall(function()")
    w('\tlocal map = require(game:GetService("ServerScriptService").Server.Map)')
    w("\tmap.init({})")
    w("\tmap.start()")
    w("end)")
    w("")
    w("if recording then")
    w("\tpcall(function()")
    w("\t\tChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit)")
    w("\tend)")
    w("end")
    w("")
    w('print(string.rep("=", 60))')
    w('print("[Starfall Valley] Installed " .. created .. " scripts.")')
    w("if previewOk then")
    w('\tprint("[Starfall Valley] The world is built. Press Play (F5) to start catching stars!")')
    w("else")
    w('\tprint("[Starfall Valley] Press Play (F5); the world builds itself when the game starts.")')
    w('\tprint("[Starfall Valley] (Preview skipped: " .. tostring(previewErr) .. ")")')
    w("end")
    w('print("[Starfall Valley] Then: File > Publish to Roblox, and turn on saving in")')
    w('print("  Game Settings > Security > Enable Studio Access to API Services.")')
    w('print(string.rep("=", 60))')
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(GAME)}: {total_files} scripts, {OUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
