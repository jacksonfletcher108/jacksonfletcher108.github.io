local function serviceAt(path)
	local node = game:GetService(path[1])
	for i = 2, #path do
		node = node:FindFirstChild(path[i]) or node:WaitForChild(path[i], 5)
	end
	return node
end

-- Replaces our own earlier install; renames anything else with the same
-- name instead of deleting it, so nothing of yours is ever lost.
local function freeName(parent, name)
	local existing = parent:FindFirstChild(name)
	while existing do
		if existing:GetAttribute(TAG) then
			existing:Destroy()
		else
			existing.Name = name .. "_Backup"
			print("[Starfall Valley] Renamed your existing " .. parent.Name .. "." .. name .. " to " .. name .. "_Backup")
		end
		existing = parent:FindFirstChild(name)
	end
end

local function make(className, name, parent, source)
	local instance = Instance.new(className)
	instance.Name = name
	if source then
		instance.Source = source
	end
	instance:SetAttribute(TAG, true)
	instance.Parent = parent
	return instance
end

