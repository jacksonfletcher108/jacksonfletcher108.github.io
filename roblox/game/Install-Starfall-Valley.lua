		local sideOffset = BRIDGE_WIDTH / 2 + sideLength / 2
		invisibleWall(
			Vector3.new(2, WALL_HEIGHT, sideLength),
			center + Vector3.new(-HALF - 1, WALL_HEIGHT / 2, sideOffset),
			folder
		)
