			local now = os.clock()
			local dt = now - last
			last = now
			local ok, err = pcall(function()
				local byZone = catchTick()
				spawnTick(byZone, dt)
			end)
			if not ok then
				warn("[Stars] " .. tostring(err))
			end
		end
	end)
end

return Stars
