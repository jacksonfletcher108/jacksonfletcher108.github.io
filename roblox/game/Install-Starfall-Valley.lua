	label.MaxDistance = 400
	label.Size = UDim2.fromOffset(360, 70)

	-- side walls (front and back) so you can't fall off
	invisibleWall(
		Vector3.new(Config.ZoneSize, WALL_HEIGHT, 2),
		center + Vector3.new(0, WALL_HEIGHT / 2, HALF + 1),
		folder
	)
	invisibleWall(
		Vector3.new(Config.ZoneSize, WALL_HEIGHT, 2),
		center + Vector3.new(0, WALL_HEIGHT / 2, -HALF - 1),
		folder
